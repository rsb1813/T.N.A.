"""F-16P Viper (F-16 Block 70 이후 가상 개량형) — 플레이어 기체 `f16p`.

    blender -b --factory-startup -P tools/blender/aircraft/f16p.py -- public/models/f16p.glb

길이 15.1 m, 폭 10.0 m(날개끝 레일 포함). 블렌디드 윙바디, 턱 흡입구, 버블 캐노피, 단일 수직꼬리, 벤트럴 핀.
선택: opt_cft (Block 60 식 컨포멀 탱크), opt_dorsal (등 스파인).
"""

import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import aero  # noqa: E402
from aero import cut, gl, nose, sec  # noqa: E402

ac = aero.Aircraft("f16p", paint=(0.19, 0.205, 0.22), paint_dark=(0.085, 0.095, 0.105), canopy="gold", seed=16)

# ------------------------------------------------------------------ 동체
SILL = 0.55
fus = nose(7.25, 1.75, 0.46, 0.44, 0.44, z=0.10, z_tip=0.03, power=0.6, count=7) + [
    sec(5.30, 0.51, 0.46, 0.50, 0.08, nb=2.3),
    sec(4.60, 0.55, 0.47, 0.50, 0.07, nb=2.6, nt=2.3),
    sec(3.70, 0.58, 0.49, 0.52, 0.06, nb=2.8, nt=2.4),
    sec(2.70, 0.63, 0.52, 0.55, 0.04, nb=3.0, nt=2.5),
    sec(1.80, 0.71, 0.58, 0.58, 0.02, nb=3.0, nt=2.6),
    sec(0.80, 0.79, 0.62, 0.60, 0.0, nb=3.0, nt=2.6),
    sec(-0.60, 0.81, 0.62, 0.62, 0.0, nb=3.0, nt=2.5),
    sec(-2.00, 0.78, 0.62, 0.62, 0.0, nb=2.8, nt=2.4),
    sec(-3.50, 0.70, 0.62, 0.60, 0.0, nb=2.4, nt=2.2),
    sec(-5.00, 0.62, 0.60, 0.58, 0.0),
    sec(-6.15, 0.565, 0.565, 0.565, 0.0),
]
ac.fuselage(fus, N=36, step=0.32)
# 등 혹(캐노피 뒤 → 수직꼬리)
ac.fuselage([sec(2.75, 0.0, 0.0, 0.0, 0.52), sec(2.35, 0.24, 0.20, 0.12, 0.56, n=2.2),
             sec(1.65, 0.30, 0.36, 0.14, 0.56, n=2.2), sec(0.30, 0.31, 0.30, 0.14, 0.56, n=2.3),
             sec(-1.60, 0.28, 0.18, 0.14, 0.56, n=2.3), sec(-2.80, 0.20, 0.08, 0.14, 0.56, n=2.3),
             sec(-3.30, 0.0, 0.0, 0.0, 0.56)], N=20, step=0.35)
# 피토관
ac.fuselage([sec(7.58, 0.0, 0.0, 0.0, 0.03), sec(7.52, 0.012, 0.012, 0.012, 0.03),
             sec(7.20, 0.02, 0.02, 0.02, 0.03)], N=8, mat="metal")

# 턱 흡입구 (아래 립이 앞으로 나온 '스마일') — 뒤쪽은 넓은 배(주 착륙장치 수납부)로 이어진다
ac.intake([
    dict(y=4.75, x=0, z=-0.80, w=0.50, ht=0.30, hb=0.35, nt=3.0, nb=2.6, ns=2.4),
    dict(y=3.80, x=0, z=-0.76, w=0.52, ht=0.36, hb=0.38, nt=3.0, nb=2.6, ns=2.6),
    dict(y=2.40, x=0, z=-0.70, w=0.56, ht=0.42, hb=0.44, nt=3.0, nb=2.8, ns=2.6),
    dict(y=0.60, x=0, z=-0.62, w=0.62, ht=0.42, hb=0.50, nt=3.0, nb=3.2, ns=2.6),
    dict(y=-1.20, x=0, z=-0.55, w=0.64, ht=0.40, hb=0.50, nt=3.0, nb=3.2, ns=2.6),
    dict(y=-2.80, x=0, z=-0.45, w=0.58, ht=0.40, hb=0.40, nt=3.0, nb=3.0, ns=2.6),
    dict(y=-4.30, x=0, z=-0.35, w=0.48, ht=0.35, hb=0.26, nt=3.0, nb=2.6, ns=2.4),
], side="center", N=32, lip=0.055, depth=1.5, slant=(0.0, -0.50))

# 스트레이크(LEX) — 조종석 옆에서 날개 앞전으로 휘어 들어가는 곡선
ac.wing([dict(s=0.00, le=4.60, c=4.60, t=0.03), dict(s=0.20, le=4.00, c=4.00, t=0.03),
         dict(s=0.42, le=3.00, c=3.00, t=0.032), dict(s=0.65, le=2.00, c=2.10, t=0.035),
         dict(s=0.88, le=1.12, c=1.30, t=0.04), dict(s=1.10, le=0.38, c=0.70, t=0.04)],
        x0=0.42, z0=0.04, airfoil="biconvex", m=7)

# 주익: 앞전 40°, 뒷전 거의 직선, 플래퍼론 + 앞전 플랩
WING = [dict(s=0.0, le=1.20, c=4.36, t=0.042), dict(s=4.07, le=-2.21, c=0.98, t=0.04)]
ac.wing(WING, x0=0.55, z0=0.05, m=10,
        cuts=[cut("aileron", 0.45, 2.75, 0.74), cut("flap_le", 0.95, 4.00, 0.16, edge="le")])

# 수평 스태빌레이터 (전체 가동, 하반각 -10°)
ac.wing([dict(s=0.0, le=-4.15, c=2.35, t=0.04), dict(s=2.30, le=-6.08, c=0.80, t=0.035)],
        x0=0.50, z0=0.02, dihedral=-10, airfoil="hex", m=7, part="elevator", pivot=dict(s=0.0, f=0.45))

# 수직꼬리 (등 필렛 포함) + 러더
ac.vtail([dict(s=0.0, le=-1.45, c=4.65, t=0.04), dict(s=0.40, le=-2.70, c=3.45, t=0.045),
          dict(s=2.75, le=-5.30, c=1.20, t=0.04)], x0=0.0, z0=0.55, side="center", m=8,
         cuts=[cut("rudder", 0.40, 2.30, 0.70)])
# 꼬리 끝 장비 포드 + 드래그슈트 하우징
ac.fuselage([sec(-4.95, 0.0, 0.0, 0.0, 3.32), sec(-5.15, 0.06, 0.06, 0.06, 3.32), sec(-6.55, 0.07, 0.07, 0.07, 3.30),
             sec(-6.75, 0.0, 0.0, 0.0, 3.29)], N=12, mat="paint")
ac.fuselage([sec(-5.35, 0.0, 0.0, 0.0, 0.92), sec(-5.65, 0.17, 0.17, 0.15, 0.85), sec(-6.55, 0.19, 0.19, 0.16, 0.82),
             sec(-6.75, 0.17, 0.17, 0.15, 0.82)], N=16, mat="paint")

# 벤트럴 핀 (아래로, 바깥 15°)
ac.vtail([dict(s=0.0, le=-3.30, c=1.50, t=0.05), dict(s=0.55, le=-3.85, c=0.85, t=0.05)],
         x0=0.45, z0=-0.62, cant=162, airfoil="plate", m=5)

# 노즐 (F110 계열)
ac.nozzle(x=0.0, z=0.0, y=-7.45, length=1.30, r_base=0.565, r_exit=0.47, petals=15, side="center")

# 스피드브레이크 하우징(노즐 양옆) + 상부 브레이크
ac.box((0.70, -5.75, 0.0), (0.34, 1.0, 0.22), mat="paint", side="both", taper=(1.0, 1.0))
ac.part("airbrake", (0, -5.25, 0.11), [[-1, 0, 0], [0, -1, 0], [0, 0, 1]])
ac.box((0.70, -5.82, 0.115), (0.33, 1.0, 0.03), mat="paint", side="both", part="airbrake")

# ------------------------------------------------------------------ 캐노피
ac.canopy([dict(y=5.30, w=0.30, h=0.02, z=SILL), dict(y=5.00, w=0.43, h=0.36, z=SILL),
           dict(y=4.50, w=0.48, h=0.63, z=SILL), dict(y=3.85, w=0.49, h=0.75, z=SILL),
           dict(y=3.15, w=0.47, h=0.69, z=SILL + 0.01), dict(y=2.50, w=0.41, h=0.52, z=SILL + 0.04),
           dict(y=1.95, w=0.31, h=0.33, z=SILL + 0.10), dict(y=1.60, w=0.22, h=0.12, z=SILL + 0.22)],
          N=20, frames=[2.50], hinge=(0.0, 1.75, SILL + 0.2))
ac.seat(3.55, SILL - 0.08)

# ------------------------------------------------------------------ 무장 스테이션
# 날개끝 레일 (L1/R1)
zr = ac.rail(4.68, -2.35, 0.08, length=2.9, width=0.10, height=0.13)
ac.station_pair("L1", "R1", (-4.68, -1.95, zr))
# 날개 파일런
for sid, (x, y, z) in (("2", (4.0, -1.40, -0.40)), ("3", (3.0, -1.0, -0.50)), ("4", (1.9, -0.60, -0.60))):
    yy = y - 0.35 if sid != "4" else y - 0.5
    ac.pylon(x, yy, z + (0.12 if sid == "2" else 0.0), length=1.9 if sid != "4" else 2.4, width=0.12)
    if sid == "2":
        ac.rail(x, y - 0.1, z + 0.12, length=2.3, height=0.12)
    ac.station_pair("L" + sid, "R" + sid, (-x, y, z))
# 중앙
ac.pylon(0.0, -0.55, -1.10, length=2.0, width=0.14, side="center")
ac.station("C", gl(0, -1.1, 0.4))
# 흡입구 측면 (표적/IRST 포드)
ac.pylon(0.50, 2.45, -1.20, length=1.0, width=0.10)
ac.station_pair("CHIN_L", "CHIN_R", gl(-0.5, -1.2, -2.6))

# ------------------------------------------------------------------ 선택 장비
ac.fuselage([sec(1.35, 0.0, 0.0, 0.0, 0.60, x=0.50), sec(0.95, 0.24, 0.16, 0.10, 0.60, x=0.52, n=2.4),
             sec(-0.5, 0.31, 0.22, 0.10, 0.60, x=0.55, n=2.4), sec(-2.4, 0.27, 0.19, 0.10, 0.56, x=0.53, n=2.4),
             sec(-3.4, 0.0, 0.0, 0.0, 0.54, x=0.48)], N=20, step=0.35, side="both", part="opt_cft")
ac.fuselage([sec(1.75, 0.20, 0.10, 0.10, 0.80), sec(1.0, 0.28, 0.22, 0.10, 0.82, n=2.5),
             sec(-1.6, 0.27, 0.20, 0.10, 0.78, n=2.5), sec(-3.0, 0.18, 0.10, 0.10, 0.70, n=2.5),
             sec(-3.4, 0.0, 0.0, 0.0, 0.67)], N=20, step=0.35, part="opt_dorsal")

# ------------------------------------------------------------------ 마킹 / 칠
ac.paint("paint_dark", y=(5.25, 6.4), z=(0.38, 2.0), both=False)          # 눈부심 방지
ac.insignia((-2.9, -1.1, 0.10), (0, 0, 1), size=0.62, kind="star_bar", up=(0, 1, 0))
ac.insignia((2.9, -1.1, 0.0), (0, 0, -1), size=0.62, kind="star_bar", up=(0, 1, 0))
ac.insignia((0.60, 1.6, -0.72), (1, 0, 0), size=0.42, kind="star_bar", side="both")
ac.insignia((-0.62, 3.25, 0.22), (-1, 0, 0.3), size=0.13, kind="oval", mat="intake")  # 기관포 포구

# ------------------------------------------------------------------ 기타 empty
ac.empty("gun", (-0.66, 3.30, 0.22))
ac.empty("cockpit", (0.0, 3.85, SILL + 0.50))
ac.empty("wingtip_R", (4.70, -3.0, 0.06))
ac.empty("wingtip_L", (-4.70, -3.0, 0.06))
ac.blade(0.0, 1.0, 0.86, height=0.22, chord=0.28)
for bx in (-0.16, 0.0, 0.16):  # 윈드실드 앞 IFF 안테나("버드 슬라이서")
    ac.blade(bx, 5.75, 0.45 if bx == 0 else 0.42, height=0.09, chord=0.10, sweep=20, t=0.15)
ac.blade(0.0, 2.6, -1.05, height=0.18, chord=0.22, down=True)

ac.finish()
