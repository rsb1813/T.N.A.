// src/data/ballistics.ts 기준 모델로 envelope(고도 10 km, 사수·표적 마하 0.9 정면) 에 맞춰 보정했다.
//
// 규약
//   - massKg: 1발(탱크는 빈 탱크) 질량. 기관포는 탄 1발 질량.
//   - dragArea: 외부 장착 시 1발 CdA (m², 파일런/런처 포함 근사). rcsAdd: 외부 장착 시 1발 RCS 증가 (m²).
//   - motor.propellantKg: 연기 등급별 비추력(저연기 235 s / 중간 245 s / 고연기 255 s)으로 총역적에서 계산.
//     순항미사일(터보젯)은 sustain 을 순항 추력으로, propellantKg 를 연료로 둔다.
//   - envelope(km): 공대공은 고도 10 km 정면 대치 기준. 공대지는 고도 10 km·마하 0.9 투하/발사 기준,
//     지대공은 고고도 접근 표적 기준. 해면 사거리는 대략 1/3.
//   - warhead.damage: HP 기준 (전투기 ≈ 100 HP). blastRadiusM 안에서 거리 감쇠.
import { G0 } from '../core/math';
import type { Faction } from '../core/types';
import type { UnlockReq, WeaponCategory, WeaponDef } from './schema';

const FREE: UnlockReq = { cost: 0 };
const buy = (cost: number, afterMission?: string): UnlockReq => (afterMission ? { cost, afterMission } : { cost });

const ISP: Record<'low' | 'medium' | 'high', number> = { low: 235, medium: 245, high: 255 };
type Motor = NonNullable<WeaponDef['motor']>;
type Smoke = Motor['smoke'];

const round1 = (v: number) => Math.round(v * 10) / 10;

/** 고체 로켓 (부스트/서스테인). 추력은 kN 으로 받는다 */
function rocket(boostSec: number, boostKN: number, sustainSec: number, sustainKN: number, smoke: Smoke, propellantKg?: number): Motor {
  const impulse = (boostSec * boostKN + sustainSec * sustainKN) * 1000;
  return {
    boostSec,
    boostThrustN: boostKN * 1000,
    sustainSec,
    sustainThrustN: sustainKN * 1000,
    smoke,
    propellantKg: propellantKg ?? round1(impulse / (ISP[smoke] * G0)),
  };
}

/** 일체형 로켓-램제트 (sustainKN 은 고도 10 km 기준 램제트 추력) */
function ramjet(boostSec: number, boostKN: number, sustainSec: number, sustainKN: number, propellantKg: number): Motor {
  return { boostSec, boostThrustN: boostKN * 1000, sustainSec, sustainThrustN: sustainKN * 1000, smoke: 'low', ramjet: true, propellantKg };
}

/** 터보젯 순항 (부스트 짧게, 순항 추력 장시간) */
function turbojet(cruiseKN: number, enduranceSec: number, fuelKg: number): Motor {
  return { boostSec: 1.5, boostThrustN: 12_000, sustainSec: enduranceSec, sustainThrustN: cruiseKN * 1000, smoke: 'low', propellantKg: fuelKg };
}

function gun(
  id: string,
  name: string,
  users: Faction[],
  description: string,
  g: { caliberMm: number; rpm: number; muzzleVelocity: number; damage: number; dispersionMil: number; rangeM: number },
  roundKg: number,
  category: 'gun' | 'aaa' = 'gun',
): WeaponDef {
  return { id, name, category, description, users, massKg: roundKg, dragArea: 0, rcsAdd: 0, unlock: FREE, gun: g };
}

function tank(id: string, name: string, emptyKg: number, fuelKg: number, dragArea: number, rcsAdd: number, aircraftOnly: string[], users: Faction[]): WeaponDef {
  return {
    id,
    name,
    category: 'tank',
    description: `외부 연료탱크 (연료 ${fuelKg.toLocaleString('en-US')} kg). 항속↑, 항력·중량↑, 투하 가능.`,
    users,
    massKg: emptyKg,
    dragArea,
    rcsAdd,
    model: 'fueltank',
    unlock: FREE,
    tank: { fuelKg },
    aircraftOnly,
  };
}

